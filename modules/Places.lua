-- QuestBook Places -- the lore of the place you are in, on request, with "already read" (4BI-38).
--
-- Cesar, 2026-11-23: "I am thinking about adding the zone lore to qb too"; of the options, the one on demand, "but with an
-- indicator of already read". The reader bar (modules/Guide.lua) gets a Lore link:
--   hidden        this place has no story
--   "Lore"        (in the attention colour) a story you have not asked for yet
--   "Lore (read)" you have asked for it before; a click reads it again (the audio is cached on the rig)
-- A click sends WoWAI.SendTts("place", "", "p<uiMapID>", "", { area = <name> }); the bridge (wow-relay bridge/places.js)
-- has the words and reads them in the narrator's voice, queued behind what is playing. The game only knows WHICH places
-- have a story (data/Places.lua, names only, generated by dev/places/gen.js) and which ones you asked for (saved).
-- The place is the most specific one with a story: the area you stand in, else its zone.
-- "Read" means asked for: the strip is one way, so the game cannot know the bridge really played it.
-- UNVERIFIED (client only): that GetSubZoneText() gives the area names the list uses, and that
-- C_Map.GetBestMapForUnit("player") gives (or has as a parent) the zone map ids the list is keyed by.

local _, QB = ...

local mod = QB:NewModule("places", {
  read = {},          -- ["<mapID>:<area key>"] = true ("<mapID>:" is the zone itself): the stories asked for
})

local sets = {}       -- mapID -> { [key] = true }, built from the index's "a|b|c" on first use

-- An area's key, as the list has it: lower case, a leading "the " removed, apostrophes dropped, punctuation as single spaces.
local function Norm(name)
  if type(name) ~= "string" then return "" end
  local s = name:lower():gsub("^the%s+", ""):gsub("['`\226\128\153]", ""):gsub("[^%w]+", " ")
  return (s:gsub("^%s+", ""):gsub("%s+$", ""))
end
mod.Norm = function(_, name) return Norm(name) end

local function Index() return type(QB.PlacesIndex) == "table" and QB.PlacesIndex or {} end

local function Areas(map)
  local s = sets[map]
  if s then return s end
  s = {}
  local rec = Index()[map]
  if rec and type(rec.areas) == "string" then
    for key in rec.areas:gmatch("[^|]+") do s[key] = true end
  end
  sets[map] = s
  return s
end

-- The zone map the list knows for where the player is: the player's map, or the nearest map above it that is listed.
local function ZoneMap()
  if not (C_Map and C_Map.GetBestMapForUnit) then return nil end
  local ok, map = pcall(C_Map.GetBestMapForUnit, "player")
  map = ok and map or nil
  local idx = Index()
  for _ = 1, 4 do
    if not map or map == 0 then return nil end
    if idx[map] then return map end
    local okI, info = pcall(C_Map.GetMapInfo, map)
    map = okI and info and info.parentMapID or nil
  end
  return nil
end

-- Where you are, as the most specific place with a story: { map, area (the name to send; "" = the zone), name, id, read },
-- or nil when neither the area nor its zone has one.
function mod:Current()
  local idx = Index()
  local map = ZoneMap()
  local sub = type(GetSubZoneText) == "function" and GetSubZoneText() or ""
  local key = Norm(sub)
  local function Place(m, area, name, k)
    local id = tostring(m) .. ":" .. k
    return { map = m, area = area, name = name, id = id, read = self.db.read[id] and true or false }
  end
  if key ~= "" then
    if map and Areas(map)[key] then return Place(map, sub, sub, key) end
    -- an area the list keeps under another zone (a border, or the wiki's filing): when exactly one zone has it
    local hit, n = nil, 0
    for m in pairs(idx) do if Areas(m)[key] then hit, n = m, n + 1 end end
    if n == 1 then return Place(hit, sub, sub, key) end
  end
  if map and idx[map].zone then return Place(map, "", idx[map].zone, "") end
  return nil
end

-- Ask the bridge to read the story of where you are. true when the request went out.
function mod:Read()
  local cur = self:Current()
  if not cur then QB:Say("lore: no story for this place") return false end
  local W = _G.WoWAI
  if not (type(W) == "table" and type(W.SendTts) == "function") then QB:Say("lore: the WoW AI relay addon is not loaded") return false end
  local ok, sent, err = pcall(W.SendTts, "place", "", "p" .. tostring(cur.map), "", { area = cur.area })
  if ok and sent then
    self.db.read[cur.id] = true
    QB:Say("lore: asked for the story of " .. tostring(cur.name) .. (cur.read and " (again)" or ""))
    QB:Fire("place_changed")
    return true
  end
  if err == "bad action" then QB:Say("lore: the relay addon on this machine is older than the lore (update wow-relay and copy WoWAI into AddOns)")
  else QB:Say("lore: not sent (" .. tostring(err or sent) .. ")") end
  return false
end

function mod:Counts()
  local total, read = 0, 0
  for m, rec in pairs(Index()) do
    if rec.zone then total = total + 1 end
    for _ in pairs(Areas(m)) do total = total + 1 end
  end
  for _ in pairs(self.db.read) do read = read + 1 end
  return read, total
end

local function Changed() QB:Fire("place_changed") end
mod.events.ZONE_CHANGED = Changed
mod.events.ZONE_CHANGED_INDOORS = Changed
mod.events.ZONE_CHANGED_NEW_AREA = Changed
mod.events.PLAYER_ENTERING_WORLD = Changed

QB:RegisterSlash(mod, "lore", function(rest)
  local sub = (rest or ""):lower():match("^(%S*)")
  if sub == "read" or sub == "play" then mod:Read() return end
  if sub == "forget" then
    mod.db.read = {}
    QB:Fire("place_changed")
    QB:Say("lore: every place is marked as not read")
    return
  end
  if sub ~= "" and sub ~= "status" then QB:Usage("/qb lore | read | forget   (the Lore link on the reader bar reads it too)") end
  local cur = mod:Current()
  local read, total = mod:Counts()
  QB:Say("lore: " .. (cur and (tostring(cur.name) .. ": " .. (cur.read and "already read" or "not read yet") .. " (/qb lore read)") or "no story for this place")
    .. " | " .. read .. " of " .. total .. " places read")
end, "lore: the story of the place you are in (status | read | forget); the Lore link on the reader bar shows new / read")
