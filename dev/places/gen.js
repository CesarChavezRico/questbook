// Writes data/Places.lua: WHICH places have a story (zone map ids and area keys), so the Lore link can say "nothing here",
// "new" or "read". Names only: the stories themselves are never in this repository (they are downloaded on the rig by
// wow-relay's bridge/places.js). Source of the list: the Spoken addon's Places data (github.com/rusty-key/spoken-wow,
// addons/Spoken_Places/Data/enUS/), whose lore text is from warcraft.wiki.gg (CC BY-SA 4.0).
//
//   node dev/places/gen.js                    fetch the two files from GitHub and rewrite data/Places.lua
//   node dev/places/gen.js Zones.lua Subzones.lua    the same from local copies
const fs = require('fs');
const path = require('path');
const BASE = 'https://raw.githubusercontent.com/rusty-key/spoken-wow/main/addons/Spoken_Places/Data/enUS/';

async function read(i, name) {
  if (process.argv[i]) return fs.readFileSync(process.argv[i], 'utf8');
  const res = await fetch(BASE + name);
  if (!res.ok) throw new Error(name + ' answered ' + res.status);
  return res.text();
}

(async () => {
  const zonesLua = await read(2, 'Zones.lua'), subsLua = await read(3, 'Subzones.lua');
  const zones = {};
  for (const m of zonesLua.matchAll(/^\t\[(\d+)\] = \{\n([\s\S]*?)\n\t\},?$/gm)) {
    const name = /^\s*name = "((?:[^"\\]|\\.)*)"/m.exec(m[2]);
    const full = /^\s*full = "((?:[^"\\]|\\.)*)"/m.exec(m[2]);
    if (name && full && full[1]) zones[m[1]] = name[1];
  }
  const areas = {};
  for (const z of subsLua.matchAll(/^\t\[(\d+)\] = \{\n([\s\S]*?)\n\t\},?$/gm)) {
    const keys = [];
    for (const a of z[2].matchAll(/^\t\t\["((?:[^"\\]|\\.)*)"\] = \{\n([\s\S]*?)\n\t\t\},?$/gm)) {
      const full = /^\s*full = "((?:[^"\\]|\\.)*)"/m.exec(a[2]);
      if (full && full[1]) keys.push(a[1]);
    }
    if (keys.length) areas[z[1]] = keys.sort();
  }
  const nz = Object.keys(zones).length, na = Object.values(areas).reduce((n, k) => n + k.length, 0);
  if (!nz || !na) throw new Error(`read ${nz} zones and ${na} areas: the format may have changed`);
  const q = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
  const ids = [...new Set([...Object.keys(zones), ...Object.keys(areas)])].sort((a, b) => a - b);
  const lines = [
    '-- GENERATED by dev/places/gen.js. Do not edit by hand.',
    '-- Which places have a story for the Lore link (modules/Places.lua): per zone map id, the zone\'s name and the keys of the',
    '-- areas with a story ("|"-separated; a key is the area\'s name in lower case, no leading "the", no apostrophes, punctuation',
    '-- as single spaces). Names only. The stories are downloaded on the rig (wow-relay bridge/places.js) from the Spoken addon\'s',
    '-- Places data (github.com/rusty-key/spoken-wow); their text is from warcraft.wiki.gg, CC BY-SA 4.0.',
    `-- ${nz} zones, ${na} areas.`,
    'local _, QB = ...',
    'QB.PlacesIndex = {',
    ...ids.map(id => `  [${id}] = { ${zones[id] ? 'zone = ' + q(zones[id]) + ', ' : ''}areas = ${q((areas[id] || []).join('|'))} },`),
    '}',
    '',
  ];
  fs.writeFileSync(path.join(__dirname, '..', '..', 'data', 'Places.lua'), lines.join('\n'));
  console.log(`data/Places.lua: ${nz} zones, ${na} areas`);
})().catch(e => { console.error('gen: ' + e.message); process.exit(1); });
