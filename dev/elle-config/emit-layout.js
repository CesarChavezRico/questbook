// Writes data/Layout.lua for the addon: the values that turn one EllesmereUI settings file into another.
//   node dev/elle-config/emit-layout.js <before.lua> <after.lua> "<name>"
// before = the settings file as it was, after = the same file with the layout built in the configurator.
// The output holds layout values only; never commit the two input files (they hold character names).
const fs = require('fs');
const path = require('path');
const L = require('./src/luatable.js');
const M = require('./src/model.js');

function emit(beforeText, afterText, name) {
  const a = L.parse(beforeText), b = L.parse(afterText);
  const profile = M.profileName(b);
  const p = M.patch(a.get('EllesmereUIDB'), b.get('EllesmereUIDB'));
  // the active profile's name is written as "$profile", so the layout fits whatever the profile is called
  const key = (k, i, arr) => (i === 1 && arr[0] === 'profiles' && k === profile ? '"$profile"' : L.lua(k));
  const pathLua = (arr) => '{ ' + arr.map(key).join(', ') + ' }';
  const lines = [
    '-- GENERATED by dev/elle-config/emit-layout.js. Do not edit by hand.',
    '-- The EllesmereUI layout: values to set in its saved settings, applied by /qb layout apply (modules/Loadout.lua).',
    'local _, QB = ...',
    'QB.layoutData = {',
    '  v = 1,',
    '  name = ' + L.lua(name) + ',',
    '  sets = {',
  ];
  for (const s of p.sets) lines.push('    { path = ' + pathLua(s.path) + ', value = ' + L.lua(s.value).replace(/\n/g, ' ') + ' },');
  lines.push('  },', '  removes = {');
  for (const r of p.removes) lines.push('    { path = ' + pathLua(r.path) + ' },');
  lines.push('  },', '}', '');
  return { text: lines.join('\n'), sets: p.sets.length, removes: p.removes.length };
}
module.exports = { emit };
if (require.main === module) {
  const [before, after, name] = process.argv.slice(2);
  const r = emit(fs.readFileSync(before, 'utf8'), fs.readFileSync(after, 'utf8'), name || 'layout');
  fs.mkdirSync(path.join(__dirname, '..', '..', 'data'), { recursive: true });
  fs.writeFileSync(path.join(__dirname, '..', '..', 'data', 'Layout.lua'), r.text);
  console.log('wrote data/Layout.lua:', r.sets, 'values to set,', r.removes, 'to remove');
}
