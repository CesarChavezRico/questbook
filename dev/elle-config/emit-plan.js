// Writes data/Plan.lua for the addon from a plan in plans/:  node dev/elle-config/emit-plan.js thara
const fs = require('fs');
const path = require('path');
const L = require('./src/luatable.js');

function emit(plan) {
  const slots = new Map();
  for (const [page, button, what] of plan.seats) {
    const slot = (page - 1) * 12 + button;
    if (button < 1 || button > 12 || slots.has(slot)) throw new Error('bad or repeated seat: page ' + page + ' button ' + button);
    slots.set(slot, what);
  }
  for (const [name, body] of plan.macros) {
    if (name.length > 16) throw new Error('macro name over 16 characters: ' + name);
    if (('#showtooltip\n' + body).length > 255) throw new Error('macro over 255 characters: ' + name);
  }
  const used = new Set([...slots.values()].filter((w) => w.kind === 'macro').map((w) => w.name));
  for (const n of used) if (!plan.macros.some((m) => m[0] === n)) throw new Error('a seat uses a macro the plan does not define: ' + n);
  const lines = [
    '-- GENERATED by dev/elle-config/emit-plan.js from dev/elle-config/plans/. Do not edit by hand.',
    '-- The button plan applied by /qb bars apply (modules/Loadout.lua).',
    'local _, QB = ...',
    'QB.planData = {',
    '  v = 2,',
    '  name = ' + L.lua(plan.name) + ',',
    '  macros = {',
  ];
  for (const [name, body] of plan.macros) lines.push('    { name = ' + L.lua(name) + ', body = ' + L.lua('#showtooltip\n' + body) + ' },');
  lines.push('  },', '  slots = {');
  for (const slot of [...slots.keys()].sort((a, b) => a - b)) {
    const w = slots.get(slot);
    lines.push('    [' + slot + '] = { kind = ' + L.lua(w.kind) + (w.name ? ', name = ' + L.lua(w.name) : '') + (w.id ? ', id = ' + w.id : '') + ' },');
  }
  lines.push('  },', '}', '');
  return { text: lines.join('\n'), slots: slots.size, macros: plan.macros.length };
}
module.exports = { emit };
if (require.main === module) {
  const r = emit(require('./plans/' + process.argv[2] + '.js'));
  fs.mkdirSync(path.join(__dirname, '..', '..', 'data'), { recursive: true });
  fs.writeFileSync(path.join(__dirname, '..', '..', 'data', 'Plan.lua'), r.text);
  console.log('wrote data/Plan.lua:', r.slots, 'buttons,', r.macros, 'macros');
}
